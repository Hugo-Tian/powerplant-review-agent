import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('simulate import, review, correction, refresh, new prediction and network recovery', async ({ page, request }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('这个岗位还没有推送工单')).toBeVisible()
  await page.getByRole('button', { name: '导入模拟工单（320 条）' }).click()
  await expect(page.getByRole('status')).toContainText('已为汽轮机专工导入并预测 320 条模拟工单', { timeout: 90000 })
  await page.getByRole('button', { name: '下一页' }).click()
  await expect(page.getByText('第 2 / 32 页，共 320 条')).toBeVisible()
  await page.getByRole('button', { name: '上一页' }).click()
  await page.getByRole('searchbox', { name: '搜索工单' }).fill('SYNTH-00320')
  const row = page.getByRole('row').filter({ hasText: 'SYNTH-00320' })
  await expect(row).toHaveCount(1)
  await row.locator('.order-title').click()
  await row.getByRole('button', { name: '确认', exact: true }).click()
  await page.getByRole('dialog').getByLabel('审核人').fill('作品集演示审核人')
  await page.getByRole('button', { name: '确认并保存' }).click()
  await expect(row.getByText('已确认', { exact: true })).toBeVisible()
  await row.getByRole('button', { name: '修改', exact: true }).click()
  await page.getByRole('dialog').getByLabel('修正匹配分（0–1）').fill('0.1234')
  await page.getByRole('dialog').getByLabel('推送类型').selectOption('device_group')
  await page.getByRole('dialog').getByLabel('修改理由（必填）').fill('演示：降低本次匹配优先级，保留原始评分。')
  await page.getByRole('button', { name: '保存修改' }).click()
  await expect(row.getByText('已修改', { exact: true })).toBeVisible()
  await expect(row.locator('.score')).toHaveText('0.1234')
  await page.reload()
  await page.getByRole('searchbox', { name: '搜索工单' }).fill('SYNTH-00320')
  await expect(row.locator('.score')).toHaveText('0.1234')
  await row.locator('.order-title').click()
  await expect(page.getByText('演示：降低本次匹配优先级，保留原始评分。').first()).toBeVisible()
  const stored = (await (await request.get('/orders?user_id=synthetic-turbine&limit=200')).json()).items
    .find(item => item.order.event_id === 'SYNTH-00320')
  expect(stored.latest_prediction.score).not.toBe(0.1234)
  expect(stored.effective_result.score).toBe(0.1234)
  expect(stored.history[0].feedback).toHaveLength(2)

  await page.getByRole('combobox', { name: '审核状态' }).selectOption('correct')
  await page.getByRole('searchbox', { name: '搜索工单' }).fill('')
  await expect(page.getByText('第 1 / 1 页，共 1 条')).toBeVisible()
  await page.getByRole('combobox', { name: '审核状态' }).selectOption('all')
  await mkdir('../docs/images', { recursive: true })
  await page.screenshot({ path: '../docs/images/workbench.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../docs/images/workbench-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1080 })

  await page.getByRole('button', { name: '新建工单并预测' }).click()
  await page.getByRole('dialog').getByLabel('工单标题').fill('【模拟】浏览器验证汽轮机振动异常')
  await page.getByRole('dialog').getByLabel('工单正文').fill('虚构工单：汽轮机轴承振动超标，安排检查。')
  await page.getByRole('button', { name: '保存并预测' }).click()
  await expect(page.getByRole('status')).toContainText('工单已保存并完成预测')
  await page.getByRole('searchbox', { name: '搜索工单' }).fill('浏览器验证')
  await expect(page.getByRole('row').filter({ hasText: '浏览器验证' })).toHaveCount(1)

  await page.route('**/api/orders?*', route => route.abort())
  await page.getByRole('button', { name: '刷新列表' }).click()
  await expect(page.getByRole('alert')).toContainText('无法连接服务')
  await page.unroute('**/api/orders?*')
  await page.getByRole('button', { name: '重新加载' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)

  // 行为采集 → 画像 → 按新画像重新推送
  const behaviors = await (await request.get('/users/synthetic-turbine/behaviors')).json()
  expect(behaviors.filter(b => b.event_id === 'SYNTH-00320' && b.action_type === 'detail').length).toBeGreaterThanOrEqual(2)
  await expect(page.getByLabel('当前用户画像')).toContainText('条行为')
  await page.getByRole('button', { name: '按最新画像重新推送' }).click()
  await expect(page.getByRole('status')).toContainText('已按最新画像重新评分 321 条工单', { timeout: 90000 })

  // 详情面板：相似工单与 AI 解读入口（未配置大模型时禁用）
  await page.getByRole('searchbox', { name: '搜索工单' }).fill('SYNTH-00319')
  await page.getByRole('row').filter({ hasText: 'SYNTH-00319' }).locator('.order-title').click()
  await expect(page.getByRole('heading', { name: '相似历史工单' })).toBeVisible()
  await expect(page.locator('.similar li').first()).toBeVisible()
  await expect(page.getByRole('button', { name: '生成 AI 解读' })).toBeDisabled()
  await page.getByRole('searchbox', { name: '搜索工单' }).fill('')

  // 学习与评估：指标、权重建议（样本不足）、画像建议
  await page.getByRole('button', { name: '学习与评估' }).click()
  await expect(page.getByText('已审核推送')).toBeVisible()
  await page.getByRole('button', { name: '根据审核结果计算建议权重' }).click()
  await expect(page.getByText(/至少需要 10 条/)).toBeVisible()
  await page.getByRole('button', { name: '分析人工修改记录' }).click()
  await expect(page.getByText(/已分析 1 条人工修改/)).toBeVisible()
  await page.screenshot({ path: '../docs/images/learning.png', fullPage: true })
  await page.getByRole('button', { name: '推送工作台' }).click()

  await page.getByRole('combobox', { name: '当前岗位' }).selectOption('synthetic-electric')
  await expect(page.getByText('这个岗位还没有推送工单')).toBeVisible()
  expect(errors).toEqual([])
})
